#!/usr/bin/env python3
"""Rewrites the generated part of enclos's price list (`src/prices.toml`) from
LiteLLM's price file at a pinned commit (issue #343, design §11, Usage).

    python3 -I scripts/update_prices.py --revision <40-hex LiteLLM commit> [--input FILE]
        [--prices src/prices.toml] [--summary FILE]

Reads `model_prices_and_context_window.json` at that commit (from `--input`,
else from raw.githubusercontent.com) and rewrites only the block between the
GENERATED markers. Everything outside it is kept as it is, and an entry made
by hand wins: a LiteLLM model whose id, or id without its date suffix, a hand
entry names (as its id or one of its aliases) for the same provider is left
out. Each generated entry says where it came from, `litellm@<commit>`, the
commit its rates last changed at, so a newer commit with the same rates
changes nothing. The output depends only on the input file, the revision and
the hand section: run twice, it changes nothing the second time.

enclos never runs this: the price list ships inside the binary, and enclos
fetches no price when it runs. A weekly workflow runs it and opens a pull
request, which a person reviews before any price changes.

Standard library only.
"""

import argparse
import json
import re
import sys
import tomllib
import urllib.request
from decimal import Decimal

URL = "https://raw.githubusercontent.com/BerriAI/litellm/{rev}/model_prices_and_context_window.json"
# The file is about 5 MB; a much bigger one is a mistake, not data.
MAX_BYTES = 32 * 1024 * 1024
BEGIN = "# --- BEGIN GENERATED by scripts/update_prices.py: do not edit by hand ---"
END = "# --- END GENERATED ---"
REVISION = re.compile(r"^[0-9a-f]{40}$")
# Model ids end up in TOML and on a terminal: only what real ids use.
NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:@+-]{0,127}$")
DATE_SUFFIX = re.compile(r"-(?:\d{8}|\d{4}-\d{2}-\d{2})$")
MILLION = Decimal(1_000_000)
# Per million tokens: drops float noise such as 3.0000000000000004.
STEP = Decimal("0.000001")
# LiteLLM's provider for each of enclos's, and the prefix its ids may carry.
PROVIDERS = {
    "anthropic": "anthropic",
    "openai": "openai",
    "gemini": "gemini",
    "xai": "xai",
    "deepseek": "deepseek",
    "mistral": "mistral",
}
# A chat model, or one LiteLLM lists for OpenAI's Responses API only (the
# Codex family), which bills the same.
MODES = ("chat", "responses")
# LiteLLM's per-token field for each of enclos's per-million fields, in the
# order they are written.
FIELDS = (
    ("input", "input_cost_per_token"),
    ("output", "output_cost_per_token"),
    ("cache_read", "cache_read_input_token_cost"),
    ("cache_write", "cache_creation_input_token_cost"),
)


class Refused(Exception):
    """Input this script will not turn into prices."""


def per_million(value):
    """A per-token price as a per-million one, or None when it is not a price."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return None
    if value != value or value in (float("inf"), float("-inf")) or value < 0 or value > 1:
        return None
    return (Decimal(repr(value)) * MILLION).quantize(STEP).normalize()


def number(d):
    """A rate as TOML writes it: always with a decimal point."""
    text = format(d, "f")
    return text if "." in text else text + ".0"


def bare_id(provider, key):
    """LiteLLM's key without its provider prefix, or None when it is not one
    of the provider's own ids."""
    prefix = provider + "/"
    if key.startswith(prefix):
        key = key[len(prefix):]
    if "/" in key or not NAME.match(key):
        return None
    return key


def hand_names(text):
    """`(provider, id)` for each hand entry's id and alias, and each with its
    date suffix removed."""
    outside = text.split(BEGIN)[0] + (text.split(END, 1)[1] if END in text else "")
    try:
        doc = tomllib.loads(outside)
    except tomllib.TOMLDecodeError as e:
        raise Refused("the hand section is not TOML: {}".format(e))
    names = set()
    for entry in doc.get("models", []):
        provider = entry.get("provider")
        for name in [entry.get("id")] + list(entry.get("aliases", [])):
            if isinstance(provider, str) and isinstance(name, str):
                names.add((provider, name.lower()))
                names.add((provider, DATE_SUFFIX.sub("", name.lower())))
    return names


def previous(text):
    """The generated entries already in the file, as `(provider, id)` to
    `(rates, source)`."""
    if BEGIN not in text or END not in text:
        return {}
    block = text.split(BEGIN, 1)[1].split(END, 1)[0]
    try:
        doc = tomllib.loads(block)
    except tomllib.TOMLDecodeError:
        return {}
    out = {}
    for e in doc.get("models", []):
        rates = tuple((f, Decimal(str(e[f])).normalize()) for f, _ in FIELDS if f in e)
        out[(e.get("provider"), e.get("id"))] = (rates, e.get("source"))
    return out


def entries(data, hand):
    """The generated entries: `(provider, id, rates)`, sorted, each rates a
    tuple of `(field, Decimal)`."""
    if not isinstance(data, dict):
        raise Refused("LiteLLM's file is not a JSON object")
    found = {}
    for key in sorted(data):
        raw = data[key]
        if not isinstance(raw, dict) or raw.get("mode") not in MODES:
            continue
        provider = next((p for p, theirs in PROVIDERS.items() if raw.get("litellm_provider") == theirs), None)
        if provider is None:
            continue
        name = bare_id(PROVIDERS[provider], key)
        if name is None:
            continue
        rates = []
        for ours, theirs in FIELDS:
            if raw.get(theirs) is None:
                continue
            value = per_million(raw[theirs])
            if value is None:
                raise Refused("{}: {} is not a price".format(key, theirs))
            rates.append((ours, value))
        names = dict(rates)
        if "input" not in names or "output" not in names:
            continue
        low = name.lower()
        if (provider, low) in hand or (provider, DATE_SUFFIX.sub("", low)) in hand:
            continue
        # LiteLLM may list one model under its bare id and under a prefixed
        # one: the first in key order, the bare one, is kept.
        found.setdefault((provider, low), (provider, name, tuple(rates)))
    return [found[k] for k in sorted(found)]


def render(models, revision, before):
    lines = [BEGIN, "# From LiteLLM's model_prices_and_context_window.json; each `source` is the", "# commit its rates last changed at."]
    for provider, name, rates in models:
        kept = before.get((provider, name))
        source = kept[1] if kept and kept[0] == rates and kept[1] else "litellm@" + revision
        lines.append("")
        lines.append("[[models]]")
        lines.append('provider = "{}"'.format(provider))
        lines.append('id = "{}"'.format(name))
        for field, value in rates:
            lines.append("{} = {}".format(field, number(value)))
        lines.append('source = "{}"'.format(source))
    lines.append(END)
    return "\n".join(lines)


def rewrite(text, data, revision):
    """The price list with its generated block made from `data`, and a
    summary of what changed."""
    if not REVISION.match(revision):
        raise Refused("the revision is not a 40-hex commit id")
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        raise Refused("the price list does not have one generated block")
    before = previous(text)
    models = entries(data, hand_names(text))
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    out = head + render(models, revision, before) + tail
    # What it wrote must read back as TOML.
    tomllib.loads(out)
    now = {(p, n): r for p, n, r in models}
    added = sorted(k for k in now if k not in before)
    removed = sorted(k for k in before if k not in now)
    changed = sorted(k for k in now if k in before and before[k][0] != now[k])
    summary = ["{} models from LiteLLM {}".format(len(models), revision[:12])]
    for title, keys in (("Added", added), ("Removed", removed), ("Rates changed", changed)):
        if keys:
            summary.append("")
            summary.append("{}:".format(title))
            summary.extend("- {} {}".format(p, n) for p, n in keys)
    return out, "\n".join(summary) + "\n"


def fetch(revision):
    with urllib.request.urlopen(URL.format(rev=revision), timeout=60) as response:
        body = response.read(MAX_BYTES + 1)
    if len(body) > MAX_BYTES:
        raise Refused("LiteLLM's file is larger than {} bytes".format(MAX_BYTES))
    return body


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--revision", required=True)
    parser.add_argument("--input")
    parser.add_argument("--prices", default="src/prices.toml")
    parser.add_argument("--summary")
    args = parser.parse_args(argv)
    try:
        if not REVISION.match(args.revision):
            raise Refused("the revision is not a 40-hex commit id")
        if args.input:
            with open(args.input, "rb") as f:
                body = f.read(MAX_BYTES + 1)
            if len(body) > MAX_BYTES:
                raise Refused("the input is larger than {} bytes".format(MAX_BYTES))
        else:
            body = fetch(args.revision)
        data = json.loads(body)
        with open(args.prices, encoding="utf-8") as f:
            text = f.read()
        out, summary = rewrite(text, data, args.revision)
    except (Refused, ValueError, OSError) as e:
        print("update_prices: {}".format(e), file=sys.stderr)
        return 1
    if out != text:
        with open(args.prices, "w", encoding="utf-8") as f:
            f.write(out)
    if args.summary:
        with open(args.summary, "w", encoding="utf-8") as f:
            f.write(summary)
    print(summary, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
